"""Русская морфология для сравнения текстов — общая утилита (порт из форка
DeepWiki, дорожка D).

Правило морфологии здесь одно и намеренно узкое: срезаются ИМЕННЫЕ окончания.
Спряжение не трогается — «обрабатывает» остаётся собой. Расширять это ради
сходства зачинов дороже, чем польза: пословное сравнение допускало бы
выдуманные пересборки из известных слов.
"""
from __future__ import annotations

import re

_WORD_RE = re.compile(r"[0-9A-Za-zА-Яа-яЁё]+")


_ENDINGS = ("ами", "ями", "ыми", "ими", "его", "ого", "ому", "ему",
            "ых", "их", "ов", "ев", "ам", "ям", "ах", "ях", "ой", "ей", "ую", "юю",
            "ые", "ие", "ым", "им", "ом", "ем", "ая", "яя", "ое", "ее",
            "ы", "и", "а", "я", "у", "ю", "е", "о", "м", "й", "х")
_ENDINGS_LONGEST_FIRST = tuple(sorted(_ENDINGS, key=len, reverse=True))
_MIN_STEM = 3
_VOWELS = "аеиоуыэюя"


def is_cyrillic_letter(ch: str) -> bool:
    lo = ch.lower()
    return "а" <= lo <= "я" or lo == "ё"


def _stem_word(word: str) -> str:
    """Основа одного слова. Слово без кириллицы не трогается вовсе: латинские
    идентификаторы не склоняются, и ослаблять для них сравнение значит
    подорвать точность совпадений, ради которой стемминг заводился. (Все
    окончания и гласные ниже кириллические, так что для чисто латинского
    слова нормализация и так тождественна.)"""
    if not any(is_cyrillic_letter(ch) for ch in word):
        return word.casefold()
    w = word.casefold().replace("ё", "е")
    for end in _ENDINGS_LONGEST_FIRST:
        if w.endswith(end) and len(w) - len(end) >= _MIN_STEM:
            w = w[: -len(end)]
            break
    # Без этого шага жадный срез асимметричен: «Внешний» теряет `й` и даёт
    # `внешни`, а «Внешнего» теряет `его` и даёт `внешн` — одна лексема, две
    # разные основы.
    while len(w) > _MIN_STEM and w[-1] in _VOWELS:
        w = w[:-1]
    # Та же асимметрия на целом склонении: «Модель» -> `модель`,
    # «Модели» -> `модел`. Списка окончаний для этого не хватит.
    if len(w) > _MIN_STEM and w.endswith("ь"):
        w = w[:-1]
    return w


def stem_phrase(text: str) -> str:
    """Нормализованная форма ЦЕЛОЙ строки: слова режутся той же границей, что у
    ``_WORD_RE``, и склеиваются пробелом."""
    return " ".join(_stem_word(m.group(0)) for m in _WORD_RE.finditer(text or ""))
